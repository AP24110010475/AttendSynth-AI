"""
pages/5_Machine_Learning.py — ML Demonstration page for AttendSynth AI.
"""

import streamlit as st
import pandas as pd
import numpy as np
import plotly.express as px
import plotly.figure_factory as ff
import plotly.graph_objects as go
import sys, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import config
from src.ml_model import train_risk_classifier, FEATURE_COLUMNS

st.set_page_config(page_title="Machine Learning | AttendSynth AI", page_icon="🤖", layout="wide")

css_path = os.path.join(ROOT, "assets", "style.css")
if os.path.exists(css_path):
    with open(css_path) as f:
        st.markdown(f"<style>{f.read()}</style>", unsafe_allow_html=True)

with st.sidebar:
    st.markdown("""
    <div style='text-align:center;padding:1rem 0 0.5rem;'>
        <span style='font-size:2rem;'>🎓</span>
        <h2 style='margin:0.3rem 0 0;font-size:1.1rem;color:#3a3a6e;font-weight:700;'>AttendSynth AI</h2>
    </div><hr style='margin:0.8rem 0;'>
    """, unsafe_allow_html=True)
    # ML hyperparameters
    st.markdown("### ⚙️ Model Settings")
    n_trees    = st.slider("Number of Trees", 10, 300, config.ML_N_ESTIMATORS, 10)
    test_split = st.slider("Test Set Size (%)", 10, 40, 25, 5)
    ml_seed    = st.number_input("Random Seed", 0, 99999, config.ML_RANDOM_STATE)

st.markdown("""
<div class='page-header'>
    <h1>🤖 Machine Learning Demonstration</h1>
    <p>Random Forest classifier trained on the synthetic dataset to predict student risk categories.</p>
</div>
""", unsafe_allow_html=True)

df: pd.DataFrame | None = st.session_state.get("df")

if df is None:
    st.warning("⚠️ No dataset found.  Please generate one on the **🔧 Generator** page first.")
    st.stop()

# ── Important disclaimer ───────────────────────────────────────────────────────
st.warning("""
⚠️ **Important Disclaimer:**
This module is a **demonstration only**.  The model is trained on synthetic data
generated by the same rules used to create risk labels — so high accuracy is expected
and does **not** indicate real-world predictive power.
Never use this model on real student records without proper validation.
""")

if len(df) < 50:
    st.error("Dataset must contain at least 50 records for ML demonstration.")
    st.stop()

# ── Feature explanation ────────────────────────────────────────────────────────
with st.expander("📋 Features Used (no target leakage)"):
    st.markdown(f"""
    **Target:** `risk_category` (Low / Medium / High)

    **Input features (risk_score excluded to prevent leakage):**
    {', '.join(f'`{c}`' for c in FEATURE_COLUMNS)}
    """)

# ── Train button ──────────────────────────────────────────────────────────────
if st.button("🚀 Train Random Forest Classifier", type="primary"):
    with st.spinner("Training model…"):
        result = train_risk_classifier(
            df,
            test_size=test_split / 100,
            n_estimators=int(n_trees),
            random_state=int(ml_seed),
        )
    st.session_state["ml_result"] = result

# ── Results ────────────────────────────────────────────────────────────────────
result = st.session_state.get("ml_result")

if result is None:
    st.info("👆 Click **Train Random Forest Classifier** to run the ML demonstration.")
elif "error" in result:
    st.error(f"❌ {result['error']}")
else:
    st.success(f"✅ Model trained on {result['train_size']:,} samples | Tested on {result['test_size']:,} samples")

    # KPI metrics
    st.markdown("### 📊 Model Performance Metrics")
    m1, m2, m3, m4 = st.columns(4)
    m1.metric("Accuracy",         f"{result['accuracy']}%")
    m2.metric("F1 Score (macro)", f"{result['f1_macro']}%")
    m3.metric("Precision",        f"{result['precision_macro']}%")
    m4.metric("Recall",           f"{result['recall_macro']}%")

    st.markdown("---")

    # Classification report
    with st.expander("📋 Full Classification Report"):
        report_dict = result["classification_report"]
        rows = []
        for label in result["class_names"]:
            r = report_dict.get(label, {})
            rows.append({
                "Class":     label,
                "Precision": f"{r.get('precision',0)*100:.1f}%",
                "Recall":    f"{r.get('recall',0)*100:.1f}%",
                "F1-Score":  f"{r.get('f1-score',0)*100:.1f}%",
                "Support":   int(r.get("support", 0)),
            })
        st.dataframe(pd.DataFrame(rows), use_container_width=True)

    # Charts
    chart_col1, chart_col2 = st.columns(2)

    with chart_col1:
        # Confusion matrix
        st.markdown("#### Confusion Matrix")
        cm    = result["confusion_matrix"]
        names = result["class_names"]
        fig_cm = px.imshow(
            cm,
            labels=dict(x="Predicted", y="Actual", color="Count"),
            x=names, y=names,
            color_continuous_scale="Blues",
            text_auto=True,
            title="Confusion Matrix",
        )
        fig_cm.update_layout(height=360, template=config.CHART_TEMPLATE,
                              margin=dict(l=20, r=20, t=50, b=20))
        st.plotly_chart(fig_cm, use_container_width=True)

    with chart_col2:
        # Feature importance
        st.markdown("#### Feature Importance")
        fi_df = result["feature_importance"]
        fig_fi = px.bar(
            fi_df,
            x="importance", y="feature",
            orientation="h",
            color="importance",
            color_continuous_scale=["#c8d6f5", "#4F8EF7"],
            labels={"importance": "Importance", "feature": "Feature"},
            title="Feature Importance (Random Forest)",
        )
        fig_fi.update_layout(height=360, template=config.CHART_TEMPLATE,
                              margin=dict(l=20, r=20, t=50, b=20),
                              showlegend=False)
        st.plotly_chart(fig_fi, use_container_width=True)

    st.markdown("---")
    st.markdown("### 🧾 Model Limitations")
    st.markdown("""
    - **Synthetic training bias:** The model learns patterns from synthetically generated data, not real student behaviour.
    - **Perfect label alignment:** Risk categories were derived from the same variables used as features, so high accuracy is expected by design.
    - **No real-world validation:** Accuracy on synthetic data does not establish real-world predictive accuracy.
    - **Class imbalance:** Results may differ significantly on real datasets with different risk proportions.
    - **Ethical considerations:** Any real deployment requires rigorous ethical review and human oversight.
    """)
